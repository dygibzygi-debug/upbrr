"""Generate the Go table of letters whose Unicode name starts with "LATIN".

The Zulea tracker-name rule treats a title as Latin when every letter
(str.isalpha) has a Unicode name beginning with "LATIN". Go has no character
name table, so the exact set is generated from Python's unicodedata.

Usage: python3 scripts/zulea/gen_latin_letters.py > internal/zulea/names/latin_letters.go
"""
import sys
import unicodedata


def main() -> int:
    ranges = []
    start = prev = None
    for cp in range(sys.maxunicode + 1):
        ch = chr(cp)
        ok = ch.isalpha() and unicodedata.name(ch, "").startswith("LATIN")
        if ok:
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                ranges.append((start, prev))
                start = prev = cp
    if start is not None:
        ranges.append((start, prev))
    out = sys.stdout
    out.write("// Code generated by scripts/zulea/gen_latin_letters.py; DO NOT EDIT.\n\n")
    out.write("// Copyright (c) 2026, Zulea contributors.\n// SPDX-License-Identifier: GPL-2.0-or-later\n\n")
    out.write("package names\n\n")
    out.write(f"// latinNameUnicodeVersion is the Python unicodedata version used to build latinLetterRanges.\n")
    out.write(f'const latinNameUnicodeVersion = "{unicodedata.unidata_version}"\n\n')
    out.write("// latinLetterRanges lists inclusive code-point ranges of letters whose Unicode name starts with LATIN.\n")
    out.write("var latinLetterRanges = [][2]rune{\n")
    for a, b in ranges:
        out.write(f"\t{{0x{a:04X}, 0x{b:04X}}},\n")
    out.write("}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

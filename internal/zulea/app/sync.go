// SyncRequest copies the root-only TM inputs into an uploader-readable tree
// (deployment option "copy", see scripts/zulea/docker/README.md).
type SyncRequest struct {
	// FreezeSrc is the active freeze file; FreezeSHA256 is its expected digest.
	FreezeSrc    string
	FreezeSHA256 string
	// RunsSrc is the TM batch runs directory (<RUN_ID>/manifest-*.tsv).
	RunsSrc string
	// TitlesSrc is tmdb-titles.tsv (optional).
	TitlesSrc string
	// Dest receives freeze/, runs/<RUN_ID>/ and titles/.
	Dest string
	// Owner sets uid:gid on everything written (requires root); nil keeps the caller.
	Owner *[2]int
}

// SyncResult lists what happened, by destination path.
type SyncResult struct {
	Copied     []string `json:"copied"`
	Unchanged  []string `json:"unchanged"`
	Incomplete []string `json:"incomplete_skipped"`
}

const maxSyncFile = 64 << 20

var (
	syncRunPattern      = regexp.MustCompile(`^[A-Za-z0-9._-]{1,64}$`)
	syncManifestPattern = regexp.MustCompile(`^manifest-[0-9]{8}-[0-9]{6}\.tsv$`)
)

// SyncInputs performs the copy. Sources are only read. An existing different
// freeze or completed manifest is never overwritten (evidence is immutable);
// manifests of running batches (no "# KONIEC=" line) are skipped.
func SyncInputs(req SyncRequest) (SyncResult, error) {
	var res SyncResult
	if req.Dest == "" || !filepath.IsAbs(req.Dest) {
		return res, errors.New("sync: absolute destination is required")
	}
	if req.Owner != nil && os.Geteuid() != 0 {
		return res, errors.New("sync: setting the owner requires root")
	}
	if req.FreezeSrc != "" {
		data, err := readSource(req.FreezeSrc)
		if err != nil {
			return res, err
		}
		if digest(data) != strings.TrimSpace(req.FreezeSHA256) {
			return res, fmt.Errorf("sync: freeze SHA-256 %s != expected %s", digest(data), req.FreezeSHA256)
		}
		dst := filepath.Join(req.Dest, "freeze", filepath.Base(req.FreezeSrc))
		if err := place(req.Dest, dst, data, 0o400, req.Owner, false, &res); err != nil {
			return res, err
		}
	}
	if req.RunsSrc != "" {
		runs, err := os.ReadDir(req.RunsSrc)
		if err != nil {
			return res, fmt.Errorf("sync: list runs: %w", err)
		}
		for _, run := range runs {
			if !run.IsDir() || run.Type()&fs.ModeSymlink != 0 || !syncRunPattern.MatchString(run.Name()) || run.Name() == "." || run.Name() == ".." {
				continue
			}
			files, err := os.ReadDir(filepath.Join(req.RunsSrc, run.Name()))
			if err != nil {
				return res, fmt.Errorf("sync: list run %s: %w", run.Name(), err)
			}
			names := make([]string, 0, len(files))
			for _, f := range files {
				if syncManifestPattern.MatchString(f.Name()) {
					names = append(names, f.Name())
				}
			}
			sort.Strings(names)
			for _, name := range names {
				data, err := readSource(filepath.Join(req.RunsSrc, run.Name(), name))
				if err != nil {
					return res, err
				}
				dst := filepath.Join(req.Dest, "runs", run.Name(), name)
				if !bytes.Contains(data, []byte("\n# KONIEC=")) {
					res.Incomplete = append(res.Incomplete, dst)
					continue
				}
				if err := place(req.Dest, dst, data, 0o400, req.Owner, false, &res); err != nil {
					return res, err
				}
			}
		}
	}
	if req.TitlesSrc != "" {
		data, err := readSource(req.TitlesSrc)
		if err != nil {
			return res, err
		}
		if _, err := names.ParseTitles(data); err != nil {
			return res, fmt.Errorf("sync: titles file invalid: %w", err)
		}
		// The titles file is regenerated by the Release Panel, so a newer valid version replaces the copy.
		if err := place(req.Dest, filepath.Join(req.Dest, "titles", "tmdb-titles.tsv"), data, 0o400, req.Owner, true, &res); err != nil {
			return res, err
		}
	}
	return res, nil
}

func digest(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func readSource(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, fmt.Errorf("sync: %w", err)
	}
	if info.Mode()&fs.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return nil, fmt.Errorf("sync: %s is not a regular file", path)
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("sync: %w", err)
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, maxSyncFile+1))
	if err != nil {
		return nil, fmt.Errorf("sync: read %s: %w", path, err)
	}
	if len(data) > maxSyncFile {
		return nil, fmt.Errorf("sync: %s is too large", path)
	}
	return data, nil
}

// place writes data to dst atomically with mode, unless dst already holds the
// same bytes. A different existing file is an error unless replace is set.
func place(root, dst string, data []byte, mode os.FileMode, owner *[2]int, replace bool, res *SyncResult) error {
	if existing, err := os.ReadFile(dst); err == nil {
		if bytes.Equal(existing, data) {
			res.Unchanged = append(res.Unchanged, dst)
			return nil
		}
		if !replace {
			return fmt.Errorf("sync: %s already exists with different content; evidence is never overwritten", dst)
		}
	}
	dir := filepath.Dir(dst)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("sync: %w", err)
	}
	if owner != nil {
		// Own every directory from the destination root down to dir.
		if !pathing.IsWithinRoot(root, dir) {
			return fmt.Errorf("sync: %s escapes the destination", dst)
		}
		rel, err := filepath.Rel(root, dir)
		if err != nil {
			return fmt.Errorf("sync: %w", err)
		}
		d := root
		for _, part := range append([]string{""}, strings.Split(rel, string(filepath.Separator))...) {
			if part != "" && part != "." {
				d = filepath.Join(d, part)
			}
			if err := os.Chown(d, owner[0], owner[1]); err != nil {
				return fmt.Errorf("sync: chown %s: %w", d, err)
			}
		}
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(dst)+".tmp-*")
	if err != nil {
		return fmt.Errorf("sync: %w", err)
	}
	tmpPath := tmp.Name()
	defer func() { _ = os.Remove(tmpPath) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("sync: write: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("sync: sync: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("sync: close: %w", err)
	}
	if err := os.Chmod(tmpPath, mode); err != nil {
		return fmt.Errorf("sync: chmod: %w", err)
	}
	if owner != nil {
		if err := os.Chown(tmpPath, owner[0], owner[1]); err != nil {
			return fmt.Errorf("sync: chown: %w", err)
		}
	}
	if err := os.Rename(tmpPath, dst); err != nil {
		return fmt.Errorf("sync: replace: %w", err)
	}
	copied, err := os.ReadFile(dst)
	if err != nil || digest(copied) != digest(data) {
		return fmt.Errorf("sync: verification of %s failed", dst)
	}
	res.Copied = append(res.Copied, dst)
	return nil
}
